import fs from 'fs';
import path from 'path';

// 1. Registered routes in src/routes/index.tsx
const routesTsx = fs.readFileSync('src/routes/index.tsx', 'utf8');
const routeRegex = /path:\s*['"]([^'"]+)['"]/g;
let match;
const registeredRoutes = new Set(['']);
while ((match = routeRegex.exec(routesTsx)) !== null) {
  registeredRoutes.add(match[1]);
}
console.log('Total registered routes in index.tsx:', registeredRoutes.size);

// 2. Sitemap URLs
const sitemap = fs.readFileSync('public/sitemap.xml', 'utf8');
const locMatches = [...sitemap.matchAll(/<loc>(.*?)<\/loc>/g)].map(m => m[1]);

const sitemapMissingFromRoutes = [];
for (const loc of locMatches) {
  let urlPath = loc.replace('https://imageplumber.com', '');
  if (urlPath.startsWith('/')) urlPath = urlPath.slice(1);
  if (!registeredRoutes.has(urlPath)) {
    sitemapMissingFromRoutes.push({ loc, urlPath });
  }
}
console.log('Sitemap URLs missing from src/routes/index.tsx (', sitemapMissingFromRoutes.length, '):', sitemapMissingFromRoutes);

// 3. Check tools in Layout.tsx and Home.tsx against localized navigation
const layoutContent = fs.readFileSync('src/layouts/Layout.tsx', 'utf8');
const toolMatches = [...layoutContent.matchAll(/path:\s*'(\/[^']+)'/g)].map(m => m[1]);
const uniqueToolPaths = [...new Set(toolMatches)];
console.log('\nUnique tool paths in Layout.tsx (', uniqueToolPaths.length, '):', uniqueToolPaths);

// 4. Check i18n localeMap in i18n.ts
const i18nContent = fs.readFileSync('src/utils/i18n.ts', 'utf8');
// Extract localeMap from i18n.ts
const localeMapMatch = i18nContent.match(/const localeMap: Record<string, Record<string, string>> = \{([\s\S]*?)\n  \};/);
let localeMap = {};
if (localeMapMatch) {
  const inner = localeMapMatch[1];
  const lines = inner.split('\n');
  for (const line of lines) {
    const m = line.match(/'([^']+)':\s*\{([^}]+)\}/);
    if (m) {
      const toolKey = m[1];
      const mappingsStr = m[2];
      const langEntries = [...mappingsStr.matchAll(/(\w+):\s*'([^']+)'/g)];
      localeMap[toolKey] = {};
      for (const le of langEntries) {
        localeMap[toolKey][le[1]] = le[2];
      }
    }
  }
}
console.log('\nTools in localeMap:', Object.keys(localeMap).length);

// 5. Test getLocalizedToolPath for each tool in Layout across all 5 languages
const locales = ['es', 'pt', 'hi', 'fr', 'de'];
const brokenLinks = [];
for (const toolPath of uniqueToolPaths) {
  const toolKey = toolPath.replace(/^\//, '');
  for (const loc of locales) {
    const locSlug = localeMap[toolKey]?.[loc];
    const generatedUrl = locSlug ? `${loc}/${locSlug}` : `${loc}${toolPath}`;
    if (!registeredRoutes.has(generatedUrl)) {
      brokenLinks.push({
        toolPath,
        toolKey,
        locale: loc,
        hasLocaleMapping: !!locSlug,
        generatedUrl: `/${generatedUrl}`,
        registeredInRoutes: false
      });
    }
  }
}

console.log(`\nFound ${brokenLinks.length} broken links generated by getLocalizedToolPath:`);
for (const bl of brokenLinks) {
  console.log(` - [${bl.locale}] ${bl.toolPath} -> ${bl.generatedUrl} (hasLocaleMapping: ${bl.hasLocaleMapping})`);
}

// 6. Check prerender.js languages and filesMap
const prerenderContent = fs.readFileSync('scripts/prerender.js', 'utf8');
for (const bl of brokenLinks) {
  // Check if prerender.js renders it
  const prerenderHas = prerenderContent.includes(`'${bl.generatedUrl.replace(/^\//, '')}'`) || prerenderContent.includes(`/${bl.generatedUrl.replace(/^\//, '')}`);
  // console.log(`Prerender has ${bl.generatedUrl}: ${prerenderHas}`);
}
